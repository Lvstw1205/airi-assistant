"""Local visual identity -> public product queries -> source-backed retail offers.

No images, full OCR, history or credentials leave the Mac through this module.
Prices are parsed from pages actually fetched, never generated by an LLM.
"""
import concurrent.futures, datetime as dt, hashlib, json, re, threading, time
from decimal import Decimal, InvalidOperation
from html.parser import HTMLParser
from urllib.parse import urlencode, urlsplit, urljoin
import camera_sources, camera_bridge, web_research

NEGATIVE = re.compile(r'보지\s*마|찍지\s*마|검색하지|찾지\s*마|촬영하지|\b(?:do not|don.t|never|stop)\b', re.I)
SHOP = re.compile(r'얼마|가격|최저|저렴|싼\s*곳|싸게|어디.{0,8}(?:팔|파|사|살)|판매처|구매처|상품\s*검색|제품\s*검색|찾아줘|찾아봐|검색해|\b(?:price|cheapest|buy|shop|sold|cost|how\s+much|look\s*up|search)\b', re.I)
SHOWN = re.compile(r'이거|이게|이것|이\s*(?:물건|제품|상품)|보여|들고|카메라|홈캠|\b(?:camera|this|holding|showing)\b', re.I)

def requested(query):
    if NEGATIVE.search(query) or re.search(r'번역|예시|구현|코드|\b(?:translate|example|implement|code)\b', query, re.I): return False
    return bool(SHOWN.search(query) and SHOP.search(query))

def norm(value): return re.sub(r'[^a-z0-9가-힣]', '', str(value).casefold())

def valid_gtin(value):
    if not isinstance(value, str) or len(value) not in (8, 12, 13, 14) or not value.isascii() or not value.isdigit(): return False
    return (10 - sum(int(n) * (3 if i % 2 == 0 else 1) for i, n in enumerate(value[-2::-1])) % 10) % 10 == int(value[-1])

def identity(observation):
    p = observation.get('product') or {}
    if not isinstance(p, dict): p = {}
    # Reapply the existing label-evidence validator at this external boundary.
    import llm_client
    p = llm_client.validate_product(p)
    text = [p.get(k) for k in ('brand', 'name', 'model') if p.get(k)]
    safe = ' '.join(dict.fromkeys(text))[:180]
    if re.search(r'https?://|@|(?:password|api.?key|token|비밀번호|주민등록|계좌|여권)', safe, re.I): safe = ''
    gtin = None
    # Barcode must lie in the identified physical item's box, not elsewhere in the room.
    box = observation.get('target_bbox') or p.get('bbox')
    if p.get('identity_source') in ('physical_label', 'logo_on_item') and box:
        for b in observation.get('local_evidence', {}).get('barcodes', []):
            bb = b.get('bbox')
            if (valid_gtin(b.get('value')) and isinstance(bb, list) and len(bb) == 4
                and box[0] <= (bb[0]+bb[2])/2 <= box[2] and box[1] <= (bb[1]+bb[3])/2 <= box[3]):
                gtin = b['value']; break
    enough = bool(gtin or (safe and (p.get('name') or p.get('model'))))
    category=p.get('category','').strip()
    concrete=bool(re.search(r'\b(?:mouse|keyboard|headphones?|speaker|bottle|mug|cup|lamp|shoe|sneaker|watch|camera|charger|cable|bag|backpack|toy|figurine|book|pen|perfume|cosmetic)\b|마우스|키보드|헤드폰|이어폰|스피커|물병|텀블러|컵|머그|신발|시계|충전기|케이블|가방|장난감|향수|화장품',category,re.I))
    category_safe=bool(box and concrete and 2<=len(category)<=80 and re.fullmatch(r'[\w\s()/.,-]+',category) and not re.search(r'person|human|face|passport|prescription|credit|사람|얼굴|여권|처방|신용',category,re.I))
    return {**p, 'gtin': gtin, 'query': (gtin or safe) if enough else '', 'searchable': enough,
            'candidate_query':category if category_safe and not enough else '',
            'search_basis': 'barcode' if gtin else 'visible_label' if enough else 'unconfirmed'}

def public_url(url):
    try:
        p = urlsplit(url)
        return p.scheme == 'https' and bool(p.hostname) and not p.username and not p.password and p.port in (None, 443)
    except ValueError: return False

class ProductPage(HTMLParser):
    def __init__(self):
        super().__init__(); self.json_scripts=[]; self.current=None; self.title=[]; self.in_title=False; self.meta={}
    def handle_starttag(self, tag, attrs):
        a=dict(attrs)
        if tag == 'script' and a.get('type', '').lower().split(';')[0] == 'application/ld+json': self.current=[]
        if tag == 'title': self.in_title=True
        if tag == 'meta': self.meta[a.get('property',a.get('name',''))]=a.get('content','')
    def handle_data(self, value):
        if self.current is not None: self.current.append(value)
        if self.in_title: self.title.append(value)
    def handle_endtag(self, tag):
        if tag == 'title': self.in_title=False
        if tag == 'script' and self.current is not None:
            raw=''.join(self.current); self.current=None
            try: self.json_scripts.append(json.loads(raw))
            except (ValueError, RecursionError): pass

def nodes(value):
    if isinstance(value, list):
        for item in value: yield from nodes(item)
    elif isinstance(value, dict):
        yield value
        for key in ('@graph', 'itemListElement', 'item', 'mainEntity', 'hasVariant'):
            if key in value: yield from nodes(value[key])

def kind(node, target):
    value=node.get('@type', [])
    return target in (value if isinstance(value, list) else [value])

def money(value):
    if type(value) not in (str, int, float): return None
    s=str(value).strip()
    if not re.fullmatch(r'\d+(?:\.\d{1,4})?', s): return None
    try:
        amount=Decimal(s)
        return format(amount, 'f') if 0 < amount < 10000000 else None
    except InvalidOperation: return None

def product_match(product, wanted):
    explicit_codes=[str(product.get(k,'')) for k in ('gtin','gtin8','gtin12','gtin13','gtin14') if valid_gtin(str(product.get(k,'')))]
    if wanted.get('gtin') and explicit_codes:
        return 'same_barcode' if any(c.lstrip('0') == wanted['gtin'].lstrip('0') for c in explicit_codes) else None
    if not isinstance(product.get('name',''),str): return None
    brand=product.get('brand', '')
    if isinstance(brand, dict): brand=brand.get('name', '')
    name=norm(product.get('name',''))
    branded=bool(wanted.get('brand') and norm(wanted['brand']) in norm(str(brand)+' '+product.get('name','')))
    model=wanted.get('model')
    if branded and model and norm(model) in [norm(product.get(k,'')) for k in ('mpn','model','sku')]: return 'same_model_options_unchecked'
    if branded and model and len(model)>=3 and re.search(r'\d',model):
        pattern=r'(?<![A-Za-z0-9])'+r'[\s_-]*'.join(re.escape(x) for x in re.split(r'[\s_-]+',model))+r'(?![A-Za-z0-9])'
        if re.search(pattern,product.get('name',''),re.I):return 'same_model_options_unchecked'
    label=wanted.get('name')
    if branded and label and norm(label) in name and (not model or norm(model) in name): return 'label_match_options_unchecked'
    return None

def parse_offers(raw, url, wanted, now=None):
    now=now or dt.datetime.now(dt.timezone.utc)
    parser=ProductPage(); parser.feed(raw); result=[]
    for data in parser.json_scripts:
        for product in nodes(data):
            if not kind(product, 'Product'): continue
            basis=product_match(product, wanted)
            if not basis: continue
            offers=product.get('offers', [])
            if isinstance(offers, dict): offers=[offers]
            if not isinstance(offers, list): continue
            for offer in offers[:30]:
                if not isinstance(offer, dict) or kind(offer, 'AggregateOffer'): continue
                amount=money(offer.get('price'))
                currency=offer.get('priceCurrency')
                if not amount or not isinstance(currency, str) or not re.fullmatch(r'[A-Z]{3}', currency): continue
                until=offer.get('priceValidUntil')
                if until:
                    try:
                        if dt.date.fromisoformat(str(until)[:10]) < now.date(): continue
                    except ValueError: continue
                offer_url=urljoin(url,offer.get('url') or url)
                # Attribute only an offer served by the fetched retailer, never an injected offsite checkout URL.
                if not public_url(offer_url) or urlsplit(offer_url).hostname != urlsplit(url).hostname: continue
                availability=str(offer.get('availability','')).rsplit('/',1)[-1]
                condition=str(offer.get('itemCondition',product.get('itemCondition',''))).rsplit('/',1)[-1]
                seller=offer.get('seller',{})
                seller=seller.get('name') if isinstance(seller,dict) else seller
                result.append({'title':str(product.get('name',''))[:250], 'seller':str(seller or urlsplit(url).hostname)[:160],
                    'url':offer_url, 'source_url':url, 'price':amount, 'currency':currency,
                    'availability':availability or 'unknown', 'condition':condition or 'unknown',
                    'shipping':None, 'tax':None, 'landed_total':None, 'match_basis':basis,
                    'fetched_at':now.isoformat(), 'evidence':'retailer_product_jsonld', 'price_valid_until':until})
    return result

def comparison(offers):
    # Only identical GTIN + new + explicitly in-stock + same currency can be ranked.
    exact=[o for o in offers if o['match_basis']=='same_barcode' and o['condition']=='NewCondition' and o['availability']=='InStock']
    groups={}
    for o in exact: groups.setdefault(o['currency'], []).append(o)
    return [{'currency':currency, 'offer':min(rows,key=lambda x:Decimal(x['price'])), 'compared':len(rows),
             'basis':'item_price_only', 'is_landed_cheapest':False} for currency, rows in groups.items() if len({o['seller'] for o in rows})>=2]

def search_identity(wanted):
    stamp=dt.datetime.now(dt.timezone.utc).isoformat()
    base={'identity':wanted, 'searched_at':stamp, 'region':'Canada', 'offers':[], 'sources':[], 'errors':[], 'comparisons':[],
          'images_uploaded':False, 'price_policy':'표시 상품가만 비교. 배송비·세금·옵션·재고는 별도 확인. 전체 시장 최저가 보장 아님.'}
    if not wanted.get('searchable') and not wanted.get('candidate_query'):
        return {**base, 'status':'need_label', 'message':wanted.get('next_view') or '제품 하나의 앞면 라벨이나 모델명을 가까이 보여 줘. 정확한 제품이 확인되기 전에는 가격을 붙이지 않을게.'}
    public_identity=wanted.get('query') or wanted['candidate_query']
    query=public_identity+' Canada buy price CAD'
    base['query']=query
    base['links']=[{'title':'Google 이미지로 모양 대조', 'url':'https://www.google.com/search?'+urlencode({'tbm':'isch','q':public_identity})},
                   {'title':'Google 쇼핑에서 비교', 'url':'https://www.google.com/search?'+urlencode({'tbm':'shop','q':public_identity,'gl':'ca'})}]
    try: found=web_research.search(query,6)
    except Exception:
        return {**base, 'status':'search_unavailable', 'message':'제품 라벨은 읽었지만 지금 웹 검색에 연결하지 못했어. 확인하지 않은 판매처나 가격은 만들지 않을게.'}
    # Search snippets are links only. Numeric prices must come from fetched product pages.
    candidates=[r for r in found['results'] if public_url(r.get('url',''))][:6]
    if not wanted.get('searchable'):
        base['sources']=[{'url':r['url'],'title':r.get('title',r['url']),'page_read':False} for r in candidates]
        return {**base,'status':'visual_candidates'}
    def fetch_one(row):
        try:
            raw, resolved, truncated=web_research.fetch(row['url'])
            return ({'url':resolved,'title':row.get('title',resolved),'fetched_at':dt.datetime.now(dt.timezone.utc).isoformat(),'page_read':True,'partial':truncated},
                    parse_offers(raw,resolved,wanted))
        except Exception: return ({'url':row['url'],'title':row.get('title',row['url']),'page_read':False},[])
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        for source, rows in pool.map(fetch_one,candidates):
            base['sources'].append(source); base['offers'].extend(rows)
    seen=set(); unique=[]
    for o in base['offers']:
        key=(o['url'],o['price'],o['currency'],o['condition'])
        if key not in seen: seen.add(key); unique.append(o)
    base['offers']=sorted(unique, key=lambda o:(o['currency']!='CAD',o['currency'],Decimal(o['price'])))[:20]
    base['comparisons']=comparison(base['offers'])
    base['status']='offers_found' if base['offers'] else 'links_only'
    return base

def summary(result):
    p=result['identity']; name=p.get('query') or p.get('category') or '제품'
    if result['status'] in ('need_label','search_unavailable'): return result['message']
    if result['status']=='visual_candidates': return f"{p['candidate_query']} 형태로 보이는 물건이라 유사 제품을 검색했어. 같은 제품으로 확인한 결과는 아니야. 정확한 가격 비교를 하려면 브랜드·모델명이나 바코드를 보여 줘."
    if not result['offers']: return f'{name} 라벨을 기준으로 판매처를 검색했어. 검색 링크는 찾았지만 같은 제품의 현재 가격을 판매 페이지에서 확인하지 못했어. 링크에서 모델과 옵션을 먼저 대조해 줘.'
    text=f'{name} 기준으로 확인한 판매 정보야.\n'
    for row in result['offers'][:6]:
        text+=f"• {row['seller']}: {row['price']} {row['currency']} · {row['availability']} · {row['condition']}\n"
    if result['comparisons']:
        for c in result['comparisons']:
            o=c['offer'];text+=f"같은 바코드·새 상품·재고 있음으로 확인한 {c['compared']}개 {c['currency']} 판매 정보 중 상품 표시가는 {o['seller']}의 {o['price']} {o['currency']}가 가장 낮아.\n"
    else: text+='바코드·옵션·상태·재고까지 같은 비교 대상을 충분히 확인하지 못해서 최저가로 단정하지 않을게.\n'
    return text+'배송비와 세금은 포함하지 않았고, 최종 결제가는 판매처에서 확인해야 해.'

_LOCK=threading.Lock(); _LAST={}
def run(app, number=1, question='', automatic=False):
    number=camera_sources.camera_id(number)
    # Coalesce expensive vision + retail work, never run one per UI heartbeat.
    if not _LOCK.acquire(blocking=False): raise ValueError('제품을 이미 확인 중이야. 결과가 나온 뒤 다시 보여 줘.')
    try:
        observation=camera_sources.service(app,number).run('camera_describe',question=question or 'Identify the single held/shown product. Read its physical label, model and barcode evidence.')
        wanted=identity(observation)
        key=hashlib.sha256(norm(wanted.get('query') or wanted.get('candidate_query','')).encode()).hexdigest()
        previous=_LAST.get((str(app.DATA),number))
        if automatic and previous and previous[0]==key and time.monotonic()-previous[1]<180:
            return {**previous[2], 'repeated':True}
        result=search_identity(wanted)
        result.update(camera_id=number, camera=observation['camera'], capture_time=observation['timestamp'], description=observation['description'])
        result['text']=summary(result)
        _LAST[(str(app.DATA),number)]=(key,time.monotonic(),result)
        return result
    finally: _LOCK.release()

def stream(app, query):
    number=camera_sources.selected_id(query)
    yield {'type':'tool','name':'camera_product_search'}
    result=run(app,number,question=query)
    yield {'type':'product_results','result':result}
    yield {'type':'sources','sources':result.get('sources',[])+result.get('links',[])}
    yield {'type':'token','text':result['text']}
